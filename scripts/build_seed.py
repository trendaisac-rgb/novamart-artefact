"""Builds supabase/seed.sql from the policy markdown files and the mock orders.

Operations owns the markdown in supabase/policies/ (one "#" title, a summary
paragraph, one "##" heading per rule). Run this after editing a policy:

    python scripts/build_seed.py

The seed is idempotent (upserts), so it can be re-applied at any time.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POLICIES = ROOT / "supabase" / "policies"
ORDERS = ROOT / "supabase" / "orders.json"
OUT = ROOT / "supabase" / "seed.sql"


def q(text: str) -> str:
    """SQL dollar-quoted literal; markdown never contains the tag."""
    assert "$md$" not in text
    return f"$md${text}$md$"


def parse(path: Path):
    title, summary, sections, heading, buf = path.stem, [], [], None, []

    def flush():
        if heading and "\n".join(buf).strip():
            sections.append((heading, "\n".join(buf).strip()))

    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            title = line[2:].strip()
        elif line.startswith("## "):
            flush()
            heading, buf = line[3:].strip(), []
        elif heading is None:
            if line.strip():
                summary.append(line.strip())
        else:
            buf.append(line)
    flush()
    return title, " ".join(summary), sections


def main() -> None:
    out = ["-- Generated by scripts/build_seed.py. Edit supabase/policies/*.md, not this file.", ""]
    for path in sorted(POLICIES.glob("*.md")):
        doc_id = path.stem
        title, summary, sections = parse(path)
        out.append(
            f"insert into public.policy_documents (doc_id, title, summary) values ({q(doc_id)}, {q(title)}, {q(summary)})\n"
            f"  on conflict (doc_id) do update set title = excluded.title, summary = excluded.summary, updated_at = now();"
        )
        out.append(f"delete from public.policy_sections where doc_id = {q(doc_id)};")
        for i, (heading, body) in enumerate(sections):
            out.append(
                f"insert into public.policy_sections (doc_id, heading, body, position) values "
                f"({q(doc_id)}, {q(heading)}, {q(body)}, {i});"
            )
        out.append("")

    for order_id, data in json.loads(ORDERS.read_text(encoding="utf-8")).items():
        out.append(
            f"insert into public.orders (order_id, data) values ({q(order_id)}, {q(json.dumps(data))}::jsonb)\n"
            f"  on conflict (order_id) do update set data = excluded.data;"
        )
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
